#!/usr/bin/env python3
"""Refresh audit metadata using its retained usage snapshot, without transcripts.

The original wide estate inventory remains evidence, not current-state proof.
Only the owned monorepo sources and audit-managed global installs are rechecked.
HALO, Cam, plugins, vendor sources and other worktrees are never modified/read.
"""
import argparse
from collections import defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess

HUB = Path(__file__).resolve().parents[1]
REPO = HUB.parents[2]
OUT = HUB.parent
BASELINE = REPO / '_archive/2026-10-21-skills/audit-baseline/INDEX.json'


def generate():
    baseline = json.loads(BASELINE.read_text())
    policy = json.loads((HUB / 'registry/audit-policy.json').read_text())
    registry = json.loads((HUB / 'registry/skills_registry.json').read_text())['skills']
    canonical = {}
    registry_broken = []
    definitions = []
    for entry in registry:
        name = entry['skill_id']
        folder = REPO / entry['source_path'] if entry.get('source_path') else HUB / 'registry/skills' / entry['category'] / name
        for required in entry['files']['required']:
            if not (folder / required).is_file():
                registry_broken.append(str((folder / required).relative_to(REPO)))
        if (folder / 'SKILL.md').is_file():
            digest = hashlib.sha256((folder / 'SKILL.md').read_bytes()).hexdigest()
            canonical[name] = digest
            for alias in entry.get('aliases', []):
                canonical[alias] = digest
            definitions.append({'name': name, 'path': str((folder / 'SKILL.md').relative_to(REPO)), 'sha256': digest,
                                'status': (entry.get('metadata') or {}).get('status', 'active')})
    broken = []
    divergent = []
    installs = []
    for harness in ['.claude', '.codex', '.agents']:
        for name in policy['install_ids']:
            path = Path.home() / harness / 'skills' / name / 'SKILL.md'
            label = '~/' + str(path.relative_to(Path.home()))
            if not path.is_file():
                broken.append(label)
                continue
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            if digest != canonical[name]:
                divergent.append(label)
            installs.append({'name': name, 'path': label, 'sha256': digest})
    source_variants = defaultdict(set)
    pointers = []
    tracked = subprocess.check_output(['git', 'ls-files'], cwd=REPO, text=True).splitlines()
    for name in policy['research_names']:
        for value in tracked:
            if not value.endswith('/' + name + '/SKILL.md') or any(part in ('_archive', '_archived', 'backups') or part.startswith('.backup-') for part in Path(value).parts):
                continue
            p = REPO / value
            if not p.is_file():
                continue
            text = p.read_text()
            if '\ncanonical:' in text:
                pointers.append(value)
            else:
                source_variants[name].add(hashlib.sha256(p.read_bytes()).hexdigest())
    duplicate_groups = [name for name, hashes in source_variants.items() if len(hashes) > 1]
    current = {'managed_global_missing': len(broken), 'registry_missing_required': len(registry_broken),
               'managed_projection_divergence': len(divergent), 'reviewed_research_divergent_names': len(duplicate_groups),
               'dormant_names': len(policy['dormant_names']), 'verified_global_projections': len(installs)}
    result = {'schema_version': 2, 'generated_at': datetime.now(timezone.utc).isoformat(),
              'summary': current, 'baseline_summary': policy['baseline_summary'],
              'usage_snapshot': policy['usage_snapshot'],
              'scope': 'Owned registry/module sources and managed global projections rechecked on laptop. Mini full-file verification is recorded separately in its backup receipt. Wide estate baseline is retained, not relabeled as current.',
              'baseline_inventory': str(BASELINE.relative_to(REPO)),
              'discovery_excludes': policy['discovery_excludes'], 'dormant_names': policy['dormant_names'],
              'definitions': definitions, 'installs': installs, 'canonical_pointers': pointers,
              'issues': {'global_missing': broken, 'registry_missing': registry_broken, 'projection_divergence': divergent, 'research_duplicates': duplicate_groups},
              'top_fixes': policy['fixes']}
    lines = ['# Skills index', '', '> Generated by `python3 agents/skills/hub/scripts/build_audit_index.py`; do not edit.', '',
             'The original audit recorded **463 names, 359 with no observed use**. Its complete inventory and usage counts are preserved in',
             '[the original metadata snapshot](../../_archive/2026-10-21-skills/audit-baseline/INDEX.json). No transcripts were reread.', '',
             result['scope'], '', '## Verified fix scope', '', '| Finding | Before | Current |', '|---|---:|---:|',
             f'| Managed global missing entrypoints | 10 | {len(broken)} |',
             f'| Registry missing definitions | 2 | {len(registry_broken)} |',
             f'| Reviewed research names with divergent active definitions | 3 | {len(duplicate_groups)} |',
             f'| Dormant names, retained | 0 | {len(policy["dormant_names"])} |', '',
             'Required harness mirrors are projections, not duplicate canonical sources. Historical, vendor, plugin and HALO findings in the baseline are outside this fix scope; the original 54 divergent-name candidates are not claimed resolved.', '',
             '## Top 10 fixes, ranked', '', '| Rank | Status | Action |', '|---|---|---|']
    for fix in policy['fixes']:
        lines.append(f'| {fix["rank"]} | {fix["status"]} | {fix["action"]} |')
    lines += ['', 'Executable checks: Hub `npm test`; brain `compose-brain.mjs --check`; both-machine `sync_audit_projections.py` receipts. The sync command backs up each changed target before archiving it and uses the Hub installer, with complete support-file hash readback.', '',
              '## Discovery and compatibility', '',
              'Archive, `_archived`, backup and superseded-pointer entries are excluded from active audit discovery. Canonical compatibility pointers remain at former active research locations. `agent-setup` retains its tested refusal shim; `pm-tasks` retains its executable for consumers while `task-manager` owns the instructions.', '',
              '## Dormant skills', '',
              'Dormancy records zero observed use in the dated snapshot, not proof of no use. Registered entries carry `metadata.status: dormant` and are skipped by `skills list` and `skills search`; explicit installation and `info` remain available. Unregistered, vendor and external names are catalogued here without modifying their sources.', '']
    lines += [f'- `{name}` — status: dormant' for name in policy['dormant_names']]
    lines += ['', '## Source and projection issues', '', 'See [INDEX.json](INDEX.json) for current paths, hashes, and exact unresolved issue lists.', '']
    return result, '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result, markdown = generate()
    if args.check:
        old = json.loads((OUT / 'INDEX.json').read_text())
        old.pop('generated_at', None)
        result.pop('generated_at', None)
        assert old == result and (OUT / 'INDEX.md').read_text() == markdown, 'audit index is stale'
        print('SKILLS_AUDIT_INDEX_OK')
    else:
        (OUT / 'INDEX.json').write_text(json.dumps(result, indent=2) + '\n')
        (OUT / 'INDEX.md').write_text(markdown)
        print('SKILLS_AUDIT_REFRESH_OK ' + json.dumps(result['summary'], sort_keys=True))


if __name__ == '__main__':
    main()
